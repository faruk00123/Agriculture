products.forEach((p) => {
  const img = ART_IMAGES[p.art]
  if (img) p.imageUrl = img
})

export const productBrands = [...new Set(products.map((p) => p.brand))].sort()

export const getProduct = (id) => products.find((p) => p.id === id) || null

export const byTag = (tag) => products.filter((p) => p.tags.includes(tag))

export const byCategory = (slug) => products.filter((p) => p.category === slug)

export const bySubCategory = (slug) => products.filter((p) => p.subcategory === slug)

export const relatedTo = (product, limit = 4) =>
  products
    .filter((p) => p.id !== product.id && p.subcategory === product.subcategory)
    .slice(0, limit)

export const countByCategory = (slug) =>
  products.filter((p) => p.category === slug).length

export const countBySubCategory = (slug) =>
  products.filter((p) => p.subcategory === slug).length

export default products
